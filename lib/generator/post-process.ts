// Helper to trim text to maxLength at a word boundary
export function trimAtWordBoundary(text: string, maxLength: number): string {
  if (!text) return '';
  const trimmed = text.trim();
  if (trimmed.length <= maxLength) return trimmed;

  const sub = trimmed.substring(0, maxLength);
  const lastSpace = sub.lastIndexOf(' ');
  let out = lastSpace > maxLength * 0.4 ? sub.substring(0, lastSpace).trim() : sub.trim();
  // never end a shortened title on a dangling small word ("... desk in")
  const dangling = /\s+(a|an|the|and|or|of|on|in|at|with|for|to|by|from|into|near|over|under)$/i;
  while (dangling.test(out) && out.length > maxLength * 0.4) out = out.replace(dangling, '').trim();
  return out;
}

// Capital first letter (after a banned first word was removed, for example)
function capitalFirst(text: string): string {
  return text ? text.charAt(0).toUpperCase() + text.slice(1) : text;
}

// Clean an AI-written title: keep only letters, numbers, spaces, hyphens and apostrophes,
// collapse spaces, and remove a word that repeats right after itself.
export function cleanTitleText(text: string): string {
  if (!text) return '';
  const stripped = text
    .replace(/[^\p{L}\p{N}\s'\u2019-]/gu, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  const words = stripped.split(' ');
  const out: string[] = [];
  for (const w of words) {
    if (out.length > 0 && out[out.length - 1].toLowerCase() === w.toLowerCase()) continue;
    out.push(w);
  }
  return out.join(' ').trim();
}

// Simple singular form used only to spot singular/plural duplicates (icon / icons)
function singularKey(word: string): string {
  const w = word.toLowerCase();
  if (w.length > 4 && w.endsWith('ies')) return w.slice(0, -3) + 'y';
  if (w.length > 4 && /(s|x|z|ch|sh)es$/.test(w)) return w.slice(0, -2);
  if (w.length > 3 && w.endsWith('s') && !w.endsWith('ss')) return w.slice(0, -1);
  return w;
}

// Words no stock agency wants in titles or keywords: AI labels (agencies use their own AI checkbox or tag),
// AI tool names and file types (Adobe, Freepik and Shutterstock guidelines, checked Nov 2026)
const LABEL_PHRASES = [
  'ai generated',
  'ai-generated',
  'generated by ai',
  'generated with ai',
  'created with ai',
  'made with ai',
  'generative ai',
  'midjourney',
  'stable diffusion',
  'dall-e',
  'dalle',
];
const FILE_TYPE_WORDS = ['jpg', 'jpeg', 'png', 'eps', 'eps10', 'psd', 'tiff', 'webp'];
const escapeRe = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const LABEL_RES = [...LABEL_PHRASES, ...FILE_TYPE_WORDS].map((ph) => new RegExp(`\\b${escapeRe(ph)}\\b`, 'gi'));
const COLOR_WORDS = new Set([
  'red', 'orange', 'yellow', 'green', 'blue', 'purple', 'violet', 'pink', 'brown', 'black', 'white',
  'gray', 'grey', 'beige', 'turquoise', 'teal', 'cyan', 'magenta', 'gold', 'golden', 'silver', 'navy',
]);

// Removes AI-label words, AI tool names and file types from a title or keyword
export function stripLabels(text: string): string {
  let t = text;
  for (const re of LABEL_RES) t = t.replace(re, ' ');
  return t.replace(/\s{2,}/g, ' ').trim();
}

const KEYWORD_STOP_WORDS =new Set(['a', 'an', 'the', 'of', 'on', 'and', 'with', 'for', 'in', 'at', 'to']);

// Remove exact, case-insensitive, and singular/plural duplicates.
export function dedupeKeywordsSmart(keywords: string[]): string[] {
  const seenFull = new Set<string>();
  const result: string[] = [];

  for (const raw of keywords) {
    const kw = raw.trim().toLowerCase();
    if (!kw) continue;
    const fullKey = kw.split(/\s+/).map(singularKey).join(' ');
    if (seenFull.has(fullKey)) continue;

    seenFull.add(fullKey);
    result.push(kw);
  }
  return result;
}

// Decide the real background: user choice wins, otherwise use transparent PNG detection
function resolveBackground(options: { backgroundMode?: string; hasAlphaChannel?: boolean }): 'white' | 'transparent' | 'none' {
  if (options.backgroundMode === 'white') return 'white';
  if (options.backgroundMode === 'transparent') return 'transparent';
  return options.hasAlphaChannel ? 'transparent' : 'none';
}

// Make keywords follow the chosen style: single words, two-word phrases, or mixed (unchanged)
function applyKeywordStyle(keywords: string[], style?: string): string[] {
  if (style === 'single') {
    const words: string[] = [];
    for (const kw of keywords) {
      for (const w of kw.toLowerCase().split(/[\s-]+/)) {
        const clean = w.replace(/[^\p{L}\p{N}']/gu, '');
        if (clean.length > 1 && !KEYWORD_STOP_WORDS.has(clean)) words.push(clean);
      }
    }
    return dedupeKeywordsSmart(words);
  }
  if (style === 'double') {
    return keywords.filter((kw) => {
      const parts = kw.trim().split(/\s+/);
      return parts.length === 2 && !KEYWORD_STOP_WORDS.has(parts[0].toLowerCase());
    });
  }
  return keywords;
}

export interface PostProcessMetadataOptions {
  titleMaxLength: number;
  keywordsMaxCount: number;
  hasAlphaChannel?: boolean;
  keywordStyle?: 'mixed' | 'single' | 'double';
  backgroundMode?: 'auto' | 'white' | 'transparent';
  isPrefixEnabled?: boolean;
  titlePrefix?: string;
  isSuffixEnabled?: boolean;
  titleSuffix?: string;
  isNegativeTitleWordsEnabled?: boolean;
  negativeTitleWords?: string;
  isNegativeKeywordsEnabled?: boolean;
  negativeKeywords?: string;
  // selected stock site (adds that site's own rules)
  platform?: string;
  isAdditionalKeywordsEnabled?: boolean;
  additionalKeywords?: string[];
}

export function postProcessMetadata<
  T extends {
    title: string;
    description?: string;
    keywords: string[];
    flags?: Record<string, unknown>;
    flagReasons?: string[];
  }
>(
  item: T,
  options: PostProcessMetadataOptions
): T & {
  title: string;
  description?: string;
  keywords: string[];
  flags: Record<string, unknown>;
  flagReasons: string[];
} {
  let title = cleanTitleText(stripLabels(item.title || ''));

  // 1. Filter negative title words
  if (options.isNegativeTitleWordsEnabled && options.negativeTitleWords) {
    const banned = options.negativeTitleWords
      .split(',')
      .map((w) => w.trim().toLowerCase())
      .filter(Boolean);

    for (const b of banned) {
      const reg = new RegExp(`\\b${escapeRe(b)}\\b`, 'gi');
      title = title.replace(reg, '').replace(/\s{2,}/g, ' ').trim();
    }
  }

  // 2. Budget and apply prefix, suffix, core title, and background phrase
  const prefix = options.isPrefixEnabled && options.titlePrefix ? `${options.titlePrefix.trim()} ` : '';
  const suffix = options.isSuffixEnabled && options.titleSuffix ? ` ${options.titleSuffix.trim()}` : '';
  const fixedLength = prefix.length + suffix.length;
  const maxLen = options.titleMaxLength;
  const availableMax = Math.max(15, maxLen - fixedLength);

  // Start from the cleaned title. (Before, the raw AI title was used here, so banned title words came back.)
  let coreTitle = capitalFirst(title);

  // 3. Add the background phrase (white or transparent) to the core title if space permits
  const bg = resolveBackground(options);
  if (bg !== 'none') {
    const phrase = `isolated on ${bg} background`;
    const alreadyThere =
      bg === 'white'
        ? coreTitle.toLowerCase().includes('white background')
        : coreTitle.toLowerCase().includes('transparent');
    if (!alreadyThere) {
      const room = availableMax - phrase.length - 1;
      if (room >= 15) {
        coreTitle = `${trimAtWordBoundary(coreTitle, room)} ${phrase}`.trim();
      }
    }
  }

  // 4. Enforce available max length on core title at word boundary
  coreTitle = trimAtWordBoundary(coreTitle, availableMax);

  // 5. Combine prefix, core title, and suffix
  let finalTitle = `${prefix}${coreTitle}${suffix}`.trim();

  // Strict final enforcer: ensure combined length never exceeds maxLen
  if (finalTitle.length > maxLen) {
    const excess = finalTitle.length - maxLen;
    const newAvailable = Math.max(10, availableMax - excess);
    coreTitle = trimAtWordBoundary(coreTitle, newAvailable);
    finalTitle = `${prefix}${coreTitle}${suffix}`.trim();
    if (finalTitle.length > maxLen) {
      finalTitle = trimAtWordBoundary(finalTitle, maxLen);
    }
  }

  title = finalTitle;

  // 5. Clean and post-process keywords
  // drop keywords that are AI labels, AI tool names or file types
  let keywords = dedupeKeywordsSmart(
    (item.keywords || []).map((k) => k.trim()).filter((k) => k && stripLabels(k).length === k.replace(/\s{2,}/g, ' ').length)
  );

  // Deduplicate case-insensitively while preserving original capitalization
  const seen = new Set<string>();
  const deduplicated: string[] = [];
  for (const kw of keywords) {
    const lower = kw.toLowerCase();
    if (!seen.has(lower)) {
      seen.add(lower);
      deduplicated.push(kw);
    }
  }
  keywords = deduplicated;
  keywords = applyKeywordStyle(keywords, options.keywordStyle);
  if (bg === 'white') keywords = keywords.filter((k) => !k.toLowerCase().includes('transparent'));
  if (bg === 'transparent') keywords = keywords.filter((k) => !k.toLowerCase().includes('white background'));

  // Filter negative keywords
  if (options.isNegativeKeywordsEnabled && options.negativeKeywords) {
    const bannedKws = new Set(
      options.negativeKeywords
        .split(',')
        .map((w) => w.trim().toLowerCase())
        .filter(Boolean)
    );
    keywords = keywords.filter((k) => !bannedKws.has(k.toLowerCase()));
  }

  // Add background keywords (white or transparent) in the chosen keyword style
  if (bg !== 'none') {
    const style = options.keywordStyle || 'mixed';
    const extraBgTags =
      style === 'single'
        ? [bg, 'background', 'isolated']
        : style === 'double'
        ? [`${bg} background`, 'isolated background']
        : [`isolated on ${bg} background`, `${bg} background`];
    for (const tag of extraBgTags) {
      if (!keywords.map((k) => k.toLowerCase()).includes(tag.toLowerCase())) {
        keywords.unshift(tag);
      }
    }
  }

  // Merge additional keywords if enabled
  if (options.isAdditionalKeywordsEnabled && options.additionalKeywords && options.additionalKeywords.length > 0) {
    for (const extra of options.additionalKeywords) {
      const trimmedExtra = extra.trim();
      if (trimmedExtra && !keywords.map((k) => k.toLowerCase()).includes(trimmedExtra.toLowerCase())) {
        keywords.push(trimmedExtra);
      }
    }
  }

  // Keyword relevance check (Requirement 3):
  // Remove "ai" and "artificial intelligence" unless the image clearly shows the concept, using AI flags
  const flags = (item as { flags?: Record<string, unknown> }).flags || {};
  const aiKeywords = new Set(['ai', 'artificial intelligence', 'a.i.', 'artificial-intelligence']);
  const textToCheck = `${title} ${item.description || ''}`.toLowerCase();
  const visualShowsAiConcept =
    Boolean(flags.showsAiConcept) ||
    /\b(robot|robotics|cyborg|humanoid|android|neural network|machine learning|deep learning|cybernetic|synthetic intelligence|digital brain|microchip)\b/i.test(
      textToCheck
    );

  if (!visualShowsAiConcept) {
    keywords = keywords.filter((k) => !aiKeywords.has(k.trim().toLowerCase()));
  }

  // Freepik treats listing every colour as spam: keep at most the 2 most important colour keywords
  if (options.platform === 'freepik') {
    let colours = 0;
    keywords = keywords.filter((k) => {
      if (!COLOR_WORDS.has(k.toLowerCase())) return true;
      colours += 1;
      return colours <= 2;
    });
  }

  // Cut keywords to max count
  keywords = keywords.slice(0, options.keywordsMaxCount);

  // Synchronize visibleTextOrLogo flag
  const updatedFlags = {
    identifiablePerson: false,
    privateProperty: false,
    visibleLogoOrBrand: false,
    visibleText: false,
    visibleTextOrLogo: false,
    possibleEditorial: false,
    showsAiConcept: false,
    ...flags,
  };
  if (updatedFlags.visibleText || updatedFlags.visibleLogoOrBrand) {
    updatedFlags.visibleTextOrLogo = true;
  }

  return {
    ...item,
    title,
    description: item.description,
    keywords,
    flags: updatedFlags,
    flagReasons: (item as { flagReasons?: string[] }).flagReasons || [],
  };
}

export interface PostProcessPromptOptions {
  promptMaxLength: number;
  promptPrefix?: string;
  isPromptPrefixEnabled?: boolean;
  promptSuffix?: string;
  isPromptSuffixEnabled?: boolean;
  negativePromptWords?: string;
  isNegativePromptWordsEnabled?: boolean;
  whiteBackground?: boolean;
  cameraParams?: boolean;
}

export function postProcessPrompt(
  prompt: string,
  options: PostProcessPromptOptions
): string {
  let result = prompt || '';

  // Filter negative words
  if (options.isNegativePromptWordsEnabled && options.negativePromptWords) {
    const banned = options.negativePromptWords
      .split(',')
      .map((w) => w.trim().toLowerCase())
      .filter(Boolean);

    for (const b of banned) {
      const reg = new RegExp(`\\b${b}\\b`, 'gi');
      result = result.replace(reg, '').replace(/\s{2,}/g, ' ').trim();
    }
  }

  // Apply white background detail if enabled
  if (options.whiteBackground && !result.toLowerCase().includes('white background')) {
    result = `${result}, isolated on a pure white background`;
  }

  // Apply camera details if enabled
  if (options.cameraParams && !result.toLowerCase().includes('lens') && !result.toLowerCase().includes('aperture')) {
    result = `${result}, shot with 50mm f/1.8 lens, high dynamic range, crisp sharp focus`;
  }

  // Apply prefix & suffix
  const prefix = options.isPromptPrefixEnabled && options.promptPrefix ? `${options.promptPrefix.trim()} ` : '';
  const suffix = options.isPromptSuffixEnabled && options.promptSuffix ? ` ${options.promptSuffix.trim()}` : '';
  result = `${prefix}${result}${suffix}`.trim();

  // Enforce max length at word boundary
  return trimAtWordBoundary(result, options.promptMaxLength);
}